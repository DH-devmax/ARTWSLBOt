// Command feature_catalog keeps the native/business inventory in sync with the
// same Go definitions served to the product UI. It never connects to a service.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"

	"wangshangliao/internal/features"
)

const document = "docs/feature-catalog.md"

func cell(value string) string {
	return strings.NewReplacer("|", "\\|", "\n", " ", "\r", "").Replace(value)
}

func label(value string) string {
	if out, ok := map[string]string{
		"implemented": "已实现，待完整验收", "partial": "部分接入", "pending": "待接入",
		"accepted": "完整验收通过", "native_pending": "仅配置，原生执行待接入",
		"deferred":    "暂缓，本轮不验收",
		"unavailable": "待迁移", "web_available": "Web基础管理可用", "request_only": "仅保存申请",
	}[value]; ok {
		return out
	}
	return value
}

func render() []byte {
	var out bytes.Buffer
	out.WriteString("# 原生底座与业务模块目录\n\n")
	out.WriteString("<!-- Generated by go run ./tools/feature_catalog -write; do not edit tables by hand. -->\n\n")
	source := map[string]any{}
	for _, platform := range []string{"wsl", "lajiaoliao"} {
		source[platform] = map[string]any{
			"groups": features.NativeCatalogForPlatform(platform), "details": features.NativeDetailsForPlatform(platform),
			"acceptance": features.NativeAcceptanceForPlatform(platform), "business": features.CatalogForPlatform(platform),
			"native_usage":           features.NativeUsageForPlatform(platform),
			"mobile_samples":         features.NativeDemonstrationsForPlatform(platform),
			"assistant_actions":      features.AssistantActions(platform),
			"assistant_capabilities": features.AssistantCapabilities(platform),
		}
	}
	raw, err := json.Marshal(source)
	if err != nil {
		panic(err)
	}
	fmt.Fprintf(&out, "<!-- Catalog SHA-256: %x -->\n\n", sha256.Sum256(raw))
	out.WriteString("来源为 `internal/features`，与功能接口和WebUI共用。此目录覆盖已登记的产品范围，")
	out.WriteString("不是官方客户端全部能力声明。原生底座负责单个读取/动作；业务模块组合底座完成规则或业务流程。\n\n")
	out.WriteString("账号与人工操作单列，保留已接入入口和历史证据，不进入群管底座验收分母，也不供助手或业务模块调用。归属与协议支持、实现、受控证据及生产准入分别判断。\n\n")
	out.WriteString("能力组ID保持兼容；独立验收项将有子项的组替换为子项，不重复计数。")
	out.WriteString("受控能力组数是历史指定场景记录数，不是独立用例数；子项不继承整组通过，完整验收与业务运行分别判断。\n\n")
	for _, platform := range []struct{ id, name string }{{"wsl", "旺商聊"}, {"lajiaoliao", "辣椒聊"}} {
		allGroups := features.NativeCatalogForPlatform(platform.id)
		allDetails := features.NativeDetailsForPlatform(platform.id)
		usage := features.NativeUsageForPlatform(platform.id)
		groups := []features.NativeCapability{}
		details := []features.NativeDetail{}
		for _, item := range allGroups {
			if usage[item.ID] == features.NativeFoundation {
				groups = append(groups, item)
			}
		}
		for _, item := range allDetails {
			if usage[item.ID] == features.NativeFoundation {
				details = append(details, item)
			}
		}
		acceptance := features.NativeAcceptanceForPlatform(platform.id)
		children := map[string][]features.NativeDetail{}
		names := map[string]string{}
		for _, item := range allGroups {
			names[item.ID] = item.Name
		}
		for _, item := range details {
			children[item.ParentID] = append(children[item.ParentID], item)
		}
		total, accepted, usable, deferred, confirmed, controlled := 0, 0, 0, 0, 0, 0
		for _, group := range groups {
			if _, ok := acceptance[group.ID]; ok {
				controlled++
			}
			if group.Support == "confirmed" {
				confirmed++
			}
			if len(children[group.ID]) == 0 {
				total++
				if group.Integration == "accepted" {
					accepted++
				} else if _, ok := acceptance[group.ID]; ok {
					usable++
				}
			} else {
				for _, child := range children[group.ID] {
					if child.Integration == "deferred" {
						deferred++
						continue
					}
					total++
					if child.Integration == "accepted" {
						accepted++
					} else if child.Acceptance != nil {
						usable++
					}
				}
			}
		}
		fmt.Fprintf(&out, "## %s\n\n", platform.name)
		fmt.Fprintf(&out, "原生能力组 **%d**；独立验收项 **%d**；历史受控能力组 **%d**；指定场景可用 **%d**；完整验收通过 **%d**。\n\n",
			len(groups), total, controlled, usable, accepted)
		fmt.Fprintf(&out, "已核对支持的能力组 **%d**；本平台待核实能力组 **%d**。\n\n", confirmed, len(groups)-confirmed)
		fmt.Fprintf(&out, "暂缓子项 **%d**，保留ID及说明，不计入上述独立验收项。\n\n", deferred)
		out.WriteString("| 原生能力组 ID | 名称 | 协议支持 | 接入状态 | 历史受控范围 |\n| --- | --- | --- | --- | --- |\n")
		for _, group := range groups {
			support, result := "待核验", "尚无通过记录"
			if group.Support == "confirmed" {
				support = "已核对"
			}
			if check, ok := acceptance[group.ID]; ok {
				result = check.Result + " 尚需：" + check.Remaining
			}
			fmt.Fprintf(&out, "| `%s` | %s | %s | %s | %s |\n",
				group.ID, cell(group.Name), support, label(group.Integration), cell(result))
		}
		if samples := features.NativeDemonstrationsForPlatform(platform.id); len(samples) > 0 {
			out.WriteString("\n### 已核验移动端样本\n\n以下只记录官方客户端演示的真实接收与协议核验，不计为本站执行通过，不提高上面的受控数量或生产准入。\n\n| 能力 ID | 样本核验 | 本站待验收 |\n| --- | --- | --- |\n")
			for _, item := range append(allGroups, detailCapabilities(allDetails)...) {
				if sample, ok := samples[item.ID]; ok {
					fmt.Fprintf(&out, "| `%s` | %s | %s |\n", item.ID, cell(sample.Result), cell(sample.Remaining))
				}
			}
		}
		out.WriteString("\n### 独立子项\n\n| 子项 ID | 原生能力组 | 名称 | 接入状态 | 实现与验收边界 | 历史受控范围 |\n| --- | --- | --- | --- | --- | --- |\n")
		for _, child := range details {
			result := "尚无通过记录"
			if child.Acceptance != nil {
				result = child.Acceptance.Result + " 尚需：" + child.Acceptance.Remaining
			}
			fmt.Fprintf(&out, "| `%s` | %s | %s | %s | %s | %s |\n", child.ID,
				cell(names[child.ParentID]), cell(child.Name), label(child.Integration), cell(child.Summary), cell(result))
		}
		out.WriteString("\n### 账号与人工操作\n\n不供群管助手和业务模块调用；以下记录不计入上面的底座进度。现有人工入口仍按网站权限、原生角色及单次确认控制，未实现部分不因归类变为可操作。\n\n")
		out.WriteString("| 能力 ID | 名称 | 接入状态 | 历史受控范围 |\n| --- | --- | --- | --- |\n")
		manualParents := map[string]bool{}
		for _, item := range allDetails {
			if usage[item.ID] == features.NativeManual {
				manualParents[item.ParentID] = true
			}
		}
		for _, item := range allGroups {
			if usage[item.ID] != features.NativeManual || manualParents[item.ID] {
				continue
			}
			result := "尚无通过记录"
			if check, ok := acceptance[item.ID]; ok {
				result = check.Result + " 尚需：" + check.Remaining
			}
			fmt.Fprintf(&out, "| `%s` | %s | %s | %s |\n", item.ID, cell(item.Name), label(item.Integration), cell(result))
		}
		out.WriteString("\n文件发送沿用“不接入”的产品决定，保留 `send_file` 历史ID，不进入任一当前操作清单；语音、视频发送仍属群管底座。\n")
		for _, item := range allDetails {
			if usage[item.ID] != features.NativeManual {
				continue
			}
			result := "尚无通过记录"
			if item.Acceptance != nil {
				result = item.Acceptance.Result + " 尚需：" + item.Acceptance.Remaining
			}
			fmt.Fprintf(&out, "| `%s` | %s | %s | %s |\n", item.ID, cell(item.Name), label(item.Integration), cell(result))
		}
		out.WriteString("\n### 业务模块\n\n| 业务模块 ID | 名称 | 状态 | 原生依赖 | 边界 |\n| --- | --- | --- | --- | --- |\n")
		for _, definition := range features.CatalogForPlatform(platform.id) {
			dependencies := []string{}
			for _, id := range definition.NativeDependencies {
				dependencies = append(dependencies, names[id]+" (`"+id+"`)")
			}
			dependency := "无原生依赖"
			if len(dependencies) > 0 {
				dependency = strings.Join(dependencies, "、")
			}
			fmt.Fprintf(&out, "| `%s` | %s | %s | %s | %s |\n", definition.ID,
				cell(definition.Name), label(definition.Status), cell(dependency), cell(definition.Summary))
		}
		out.WriteString("\n### Web 群管助手动作\n\n| 动作 ID | 名称 | 原生依赖 | 业务权限 | 建议底座 | 生产准入 |\n| --- | --- | --- | --- | --- | --- |\n")
		for _, action := range features.AssistantActions(platform.id) {
			implementation := "待接通"
			if action.Implemented {
				implementation = "可生成密封建议"
			}
			admission := action.BlockReason
			if action.Production {
				admission = "已准入"
			}
			fmt.Fprintf(&out, "| `%s` | %s | `%s` | `%s` | %s | %s |\n", action.ID, cell(action.Name), action.NativeID, action.Permission, implementation, cell(admission))
		}
		out.WriteString("\n### 助手模块接入目录\n\n注册表示适配已实现，不代表开放；平台策略默认关闭，另取套餐、租户和成员权限交集。\n\n| 能力 ID | 模块 | 类别 | 工具契约 | 额外权限 |\n| --- | --- | --- | --- | --- |\n")
		for _, d := range features.AssistantCapabilities(platform.id) {
			fmt.Fprintf(&out, "| `%s` | %s | %s | `%s` | `%s` |\n", d.ID, cell(d.Module), cell(d.Category), d.InputContract, d.Permission)
		}
		out.WriteString("\n")
	}
	out.WriteString("## 同步与验收规则\n\n")
	out.WriteString("- 新增或调整能力时，同时更新原生组/子项、业务依赖和真实验收证据；未知或未验收依赖继续阻断。\n")
	out.WriteString("- 运行 `go run ./tools/feature_catalog -write` 更新本文；`go test ./tools/feature_catalog` 和CI拒绝陈旧快照。\n")
	out.WriteString("- `go run ./tools/feature_catalog -check` 可单独检查，不访问数据库、原生接口或模型。\n")
	out.WriteString("- 好友申请仅人工逐项处理；自动审批退出业务目录，旧ID和历史配置保留。原生改名片与自动名片模块、邀请入群与热群服务申请分别验收；财务台账属于业务模块，不是原生转账。\n")
	out.WriteString("- 二级安全码设置与实名认证按所有者决定暂缓，入口关闭，不计入本轮验收；保留原ID及说明。\n")
	out.WriteString("- 辣椒聊能力组与子项独立登记；待核实条目保留旧ID，不自动复制旺商聊新能力，不继承其支持、权限或通过记录。\n")
	out.WriteString("- 短信、注册、登录仍须本人显式发起；代码检查、容器健康及受控子场景不提升readiness。\n")
	out.WriteString("- 图表绿色表示已有证据的指定场景可用；完整验收单列，不改变控制准入。App原生样本只证明平台支持，尚未接入的本站读取/发送不标绿。\n")
	return out.Bytes()
}

func detailCapabilities(details []features.NativeDetail) []features.NativeCapability {
	out := make([]features.NativeCapability, len(details))
	for i, detail := range details {
		out[i] = detail.NativeCapability
	}
	return out
}

func main() {
	write := flag.Bool("write", false, "regenerate the catalog document")
	check := flag.Bool("check", false, "check the catalog document (default)")
	flag.Parse()
	if *write && *check || flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "use either -write or -check")
		os.Exit(2)
	}
	want := render()
	if *write {
		if err := os.WriteFile(document, want, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	} else if actual, err := os.ReadFile(document); err != nil || !bytes.Equal(actual, want) {
		fmt.Fprintln(os.Stderr, "feature catalog is stale; run go run ./tools/feature_catalog -write")
		os.Exit(1)
	}
	fmt.Println("Native and business catalog synchronized.")
}
